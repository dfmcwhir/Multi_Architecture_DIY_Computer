"""ay_notes.inc: the AY-3-8910 tone period of every note C1..B8 (96), for a
chip clock of 2 MHz (or the clock given): period = clock / (16 * frequency).
    python tools/gen_notes.py [clock] > ay_notes.inc     (in the ay folder)"""
import sys
clock = int(sys.argv[1]) if len(sys.argv) > 1 else 2000000
names = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B']
print('; generated by tools/gen_notes.py: tone periods for a %d Hz chip clock' % clock)
print('; note n = octave * 12 + semitone (C1 = 0 ... B8 = 95); A4 (n = 45) is 440 Hz')
ps = []
for n in range(96):
    midi = n + 24                       # C1 = MIDI 24
    f = 440.0 * 2 ** ((midi - 69) / 12)
    ps.append(min(4095, round(clock / (16 * f))))
print('AY_NOTES = 96')
print('note_lo:')
for i in range(0, 96, 12): print('        .byte   ' + ', '.join('$%02X' % (p & 255) for p in ps[i:i + 12]) + '   ; octave %d' % (i // 12 + 1))
print('note_hi:')
for i in range(0, 96, 12): print('        .byte   ' + ', '.join('$%02X' % (p >> 8) for p in ps[i:i + 12]))
