"""sndgen.py - write sound scripts for ../sfx.s from Python (used by
game_sounds.py; SMB has its own copy of these in smb/sound.py).

Notes:  c5 e5 g#4 bb3 (octave 4 has A4 = 440 Hz), r = a rest, /n = a length
in 16ths for this note and those after it, [ ... ]n = that part n times.
"""
END, PER, VOL, NOISE, MIX, SWEEP, DECAY, LOOP, NEXT, JUMP, REST, LEN = range(12)
NOTE = {'c': 0, 'd': 2, 'e': 4, 'f': 5, 'g': 7, 'a': 9, 'b': 11}


def wait(t):
    out = []
    while t > 0:
        k = min(t, 128)
        out.append(0x80 + k - 1)
        t -= k
    return out


def per(p): return [PER, p & 255, p >> 8]
def sweep(d): return [SWEEP, d & 255, (d >> 8) & 255]


def notes(text, tick):
    """note text -> (bytes, length in 16ths)"""
    out, ln, cur, total, mark = [], 2, None, 0, None
    for tok in text.replace('[', ' [ ').replace(']', ' ]').split():
        if tok == '[':
            out += [LOOP, 0]
            mark = (len(out) - 1, total)
            cur = None
            continue
        if tok.startswith(']'):
            n = int(tok[1:])
            out[mark[0]] = n
            out.append(NEXT)
            total += (total - mark[1]) * (n - 1)
            cur = None
            continue
        if '/' in tok:
            tok, l = tok.split('/')
            ln = int(l)
        if ln * tick != cur:
            cur = ln * tick
            assert cur < 256, tok
            out += [LEN, cur]
        total += ln
        if tok == 'r':
            out.append(REST)
            continue
        n, i = NOTE[tok[0]], 1
        while tok[i] in '#b':
            n += 1 if tok[i] == '#' else -1
            i += 1
        k = (int(tok[i:]) - 1) * 12 + n
        assert 0 <= k < 96, tok
        out.append(0x20 + k)
    return out, total


def jingle(tick, vol, dec, text):
    return [VOL, vol, DECAY, dec] + notes(text, tick)[0] + [END]


def emit(path, title, music, sfx):
    """write an include: music = [(name, tick, (vol, decay, melody), (vol,
    decay, bass))] (voices 0 and 1, repeating); sfx = [(name, priority,
    voice, bytes)].  MUS_name = the melody's number (the bass is + 1)."""
    o = ['; generated by ../ay/tools/game_sounds.py: %s (scripts for ay/sfx.s)' % title, '']
    labs, prio, bodies = [], [], []
    for name, tick, mel, bas in music:
        lens = []
        for part, voice, (v, d, txt) in (('A', 0, mel), ('B', 1, bas)):
            b, total = notes(txt, tick)
            lens.append(total)
            lab = 'mus_%s%s' % (name, part)
            labs.append(lab); prio.append(voice * 16)
            bodies.append((lab, [VOL, v, DECAY, d], b))
        assert lens[0] == lens[1], (title, name, lens)
    first = len(labs)
    for name, p, voice, b in sfx:
        labs.append('snd_' + name); prio.append(voice * 16 + p)
        bodies.append(('snd_' + name, None, b))
    for i, m in enumerate(music):
        o.append('MUS_%s = %d' % (m[0].upper(), i * 2))
    for i, x in enumerate(sfx):
        o.append('SND_%s = %d' % (x[0].upper(), first + i))
    o += ['', 'sfx_scripts:']
    for i in range(0, len(labs), 6):
        o.append('        .word   ' + ', '.join(labs[i:i + 6]))
    o.append('sfx_prio:                       ; the voice x 16 + the priority')
    for i in range(0, len(prio), 16):
        o.append('        .byte   ' + ', '.join('$%02X' % x for x in prio[i:i + 16]))
    size = 0
    for lab, head, body in bodies:
        o.append(lab + ':')
        if head is not None:            # music: the set-up, then the part that repeats
            o.append('        .byte   ' + ', '.join('$%02X' % x for x in head))
            o.append(lab + '_l:')
        for i in range(0, len(body), 16):
            o.append('        .byte   ' + ', '.join('$%02X' % x for x in body[i:i + 16]))
        if head is not None:
            o.append('        .byte   $%02X, <%s_l, >%s_l' % (JUMP, lab, lab))
            size += len(head) + 3
        size += len(body)
    o.append('; (%d bytes of scripts)' % size)
    open(path, 'w').write('\n'.join(o) + '\n')
    return size
