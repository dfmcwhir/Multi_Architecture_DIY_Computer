PICS = [('PIC_WILLY', f) for f in WILLY] + \
       [('PIC_' + k, f) for k in GKINDS for f in GUARD[k]] + \
       [('PIC_PORTAL', f) for f in PORTAL]

def silhouette(rows):
    """the mask: each row filled between its first and last lit pixel"""
    out = []
    for r in rows:
        if '#' in r:
            a, b = r.index('#'), r.rindex('#')
            out.append('.' * a + '#' * (b - a + 1) + '.' * (len(r) - b - 1))
        else:
            out.append(r)
    return out

def rows_bytes(rows):
    w = len(rows[0]); nb = (w + 7) // 8
    out = []
    for r in rows:
        r = r.ljust(nb * 8, '.')
        for k in range(nb):
            out.append(sum(0x80 >> i for i in range(8) if r[k * 8 + i] == '#'))
    return out

# ---- the tiles: 4 x 4 pixels = 2 block graphics characters (bit 0 top left,
# bit 1 top right, ... bit 7 bottom right) --------------------------------------
TILES = {
    phys.EMPTY:  ['....', '....', '....', '....'],
    phys.FLOOR:  ['####', '#.#.', '....', '....'],
    phys.WALL:   ['####', '#.##', '####', '##.#'],
    phys.CONV_L: ['####', '.#.#', '#.#.', '....'],
    phys.CONV_R: ['####', '#.#.', '.#.#', '....'],
    phys.CR0:    ['##.#', '.#.#', '....', '....'],
    phys.CR1:    ['#..#', '.#..', '....', '....'],
    phys.CR2:    ['#...', '..#.', '....', '....'],
    phys.HAZARD: ['.#..', '.#.#', '##.#', '.###'],
    phys.KEY:    ['.##.', '#..#', '.##.', '.#..'],
}
def tile_chars(p):
    out = []
    for half in (0, 2):
        b = 0
        for r in range(4):
            for j in range(2):
                if p[r][half + j] == '#': b |= 1 << (r * 2 + j)
        out.append(b)
    return out

def bl(vals):
    return ', '.join('$%02X' % (v & 0xFF) for v in vals)

if __name__ == '__main__':
    print('; generated by gen.py')
    names = {}
    stream = [0x1C, 0x08]                   # CLEAR, then DEFINE each picture (with a mask)
    for n, (name, rows) in enumerate(PICS):
        if name not in names: names[name] = n; print('%-12s = %d' % (name, n))
        stream += [0x1C, 0x01, n, len(rows[0]), len(rows), 1] + rows_bytes(rows) + rows_bytes(silhouette(rows))
    print('NPIC        = %d' % len(PICS))
    print('SPR_DEFS    = %d          ; %d bytes of the pool' % (len(stream), sum(2 * len(rows_bytes(r)) for n, r in PICS)))
    print('spr_defs:')
    for i in range(0, len(stream), 16): print('        .byte   ' + bl(stream[i:i + 16]))
    print('guard_pic:  ; the first picture of each kind of guardian')
    print('        .byte   ' + ', '.join('PIC_' + k for k in GKINDS))
    print('tile_l: .byte   ' + bl([tile_chars(TILES[t])[0] for t in range(10)]))
    print('tile_r: .byte   ' + bl([tile_chars(TILES[t])[1] for t in range(10)]))
    print('JTAB_LEN    = %d' % len(phys.JTAB))
    print('jtab:   .byte   ' + bl(phys.JTAB))
    print('NROOM       = %d' % len(rooms.ROOMS))
    print('room_lo: .byte  ' + ', '.join('<room%d' % i for i in range(len(rooms.ROOMS))))
    print('room_hi: .byte  ' + ', '.join('>room%d' % i for i in range(len(rooms.ROOMS))))
    print('; each room: its name (32 characters), air, Willy x, y, the portal x, y,')
    print('; the number of guardians and 7 bytes each (kind, axis 0 across / 1 up and')
    print('; down, x, y, low, high, slow; in pixels), then the 40 x 20 tiles, two to')
    print('; a byte (the first in the low 4 bits)')
    for i, r in enumerate(rooms.ROOMS):
        m, start, portal = parse(r)
        name = r['name'].center(32)
        gs = []
        for (k, ax, c, rr, lo, hi, slow) in r['guards']:
            gs += [k, 0 if ax == 'h' else 1, c * 4, rr * 4, lo * 4, hi * 4, slow]
        print('room%d:  .byte   "%s"' % (i, name))
        print('        .byte   %d, %d, %d, %d, %d, %d' % (r['air'], start[0], start[1], portal[0] * 4, portal[1] * 4, len(r['guards'])))
        if gs: print('        .byte   ' + ', '.join(str(g) for g in gs))
        packed = [m[j] | m[j + 1] << 4 for j in range(0, len(m), 2)]
        for j in range(0, len(packed), 20): print('        .byte   ' + bl(packed[j:j + 20]))
