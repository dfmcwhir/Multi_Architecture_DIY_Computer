"""Generate muncher_data.inc: the maze as tile codes and the sprites as
block graphics character pairs.  Run:  python3 gen.py > muncher_data.inc"""
from maze import full

T = {' ': 0, '.': 1, 'o': 2, '#': 3, '-': 4, 'H': 5}

def mosaic(rows):
    """4x4 drawing -> 2 block graphics bytes (left char = columns 0-1)"""
    out = []
    for c in range(2):
        b = 0
        for k in range(4):
            if rows[k][2 * c] == '#': b |= 1 << (2 * k)
            if rows[k][2 * c + 1] == '#': b |= 1 << (2 * k + 1)
        out.append(b)
    return out

SPRITES = [  # name, drawing
    ('SP_SHUT',  ['.##.', '####', '####', '.##.']),
    ('SP_UP',    ['#..#', '#..#', '####', '.##.']),
    ('SP_LEFT',  ['.##.', '..##', '..##', '.##.']),
    ('SP_DOWN',  ['.##.', '####', '#..#', '#..#']),
    ('SP_RIGHT', ['.##.', '##..', '##..', '.##.']),
    ('SP_DIE1',  ['....', '####', '####', '.##.']),
    ('SP_DIE2',  ['....', '....', '####', '.##.']),
    ('SP_DIE3',  ['....', '....', '.##.', '.##.']),
    ('SP_DIE4',  ['....', '....', '....', '.##.']),
    ('SP_GHOST1', ['.##.', '#..#', '####', '#.#.']),
    ('SP_GHOST2', ['.##.', '#..#', '####', '.#.#']),
    ('SP_SCARED1', ['.##.', '####', '#..#', '#.#.']),
    ('SP_SCARED2', ['.##.', '####', '#..#', '.#.#']),
    ('SP_EYES',  ['....', '#..#', '....', '....']),
]
TILES = [  # tile code -> drawing (walls are worked out when the maze is drawn)
    ('TL_EMPTY', ['....', '....', '....', '....']),
    ('TL_DOT',   ['....', '.##.', '.##.', '....']),
    ('TL_PILL',  ['.##.', '####', '####', '.##.']),
    ('TL_WALL',  ['....', '....', '....', '....']),
    ('TL_DOOR',  ['....', '####', '....', '....']),
    ('TL_HOUSE', ['....', '....', '....', '....']),
]

def main():
    M = full()
    print('; generated by gen.py from maze.py - do not edit')
    print('MAZE_W = %d' % len(M[0]))
    print('MAZE_H = %d' % len(M))
    print('maze_src:            ; %d rows x 40 tile codes (column 39 is outside)' % len(M))
    for r in M:
        codes = [T[ch] for ch in r] + [0]
        print('        .byte   ' + ', '.join(str(c) for c in codes))
    print('DOTS_TOTAL = %d' % sum(r.count('.') + r.count('o') for r in M))
    print()
    print('sprites:')
    for i, (name, rows) in enumerate(SPRITES):
        print('%-10s = %d' % (name, i * 2))
    for name, rows in SPRITES:
        a, b = mosaic(rows)
        print('        .byte   $%02X, $%02X       ; %s' % (a, b, name))
    print('tile_gfx:')
    for name, rows in TILES:
        a, b = mosaic(rows)
        print('        .byte   $%02X, $%02X       ; %s' % (a, b, name))

if __name__ == '__main__':
    main()
