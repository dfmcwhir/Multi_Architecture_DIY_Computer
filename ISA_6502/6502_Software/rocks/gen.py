"""Generate rocks_data.inc for SPACE ROCKS: sine table, the ship at 32
headings, rock outlines, as lists of pixel offsets.
    python gen.py > rocks_data.inc"""
import math, random

NDIR = 32

def line(p, q):
    """pixels on the line from p to q (rounded)"""
    (x0, y0), (x1, y1) = p, q
    n = int(max(abs(x1 - x0), abs(y1 - y0)) * 2) + 1
    return {(round(x0 + (x1 - x0) * i / n), round(y0 + (y1 - y0) * i / n)) for i in range(n + 1)}

def poly(pts):
    s = set()
    for i in range(len(pts)):
        s |= line(pts[i], pts[(i + 1) % len(pts)])
    return s

def ship(d):
    a = 2 * math.pi * d / NDIR
    nose = (4.4 * math.cos(a), 4.4 * math.sin(a))
    l = (3.6 * math.cos(a + 2.5), 3.6 * math.sin(a + 2.5))
    r = (3.6 * math.cos(a - 2.5), 3.6 * math.sin(a - 2.5))
    notch = (1.4 * math.cos(a + math.pi), 1.4 * math.sin(a + math.pi))
    return poly([nose, l, notch, r])

def flame(d):
    a = 2 * math.pi * d / NDIR + math.pi
    return {(round(3.6 * math.cos(a)), round(3.6 * math.sin(a))), (round(4.6 * math.cos(a)), round(4.6 * math.sin(a)))}

def rock(r, seed):
    rnd = random.Random(seed)
    n = 10 if r > 4 else 8
    pts = []
    for i in range(n):
        a = 2 * math.pi * i / n + rnd.uniform(-0.2, 0.2)
        rr = r * rnd.uniform(0.72, 1.0)
        pts.append((rr * math.cos(a), rr * math.sin(a)))
    return poly(pts)

SHAPES = []          # (name, pixel set)
for d in range(NDIR): SHAPES.append(('SH_SHIP%d' % d, ship(d)))
for d in range(NDIR): SHAPES.append(('SH_FLAME%d' % d, flame(d)))
ROCK_R = [7, 4, 2]
for size, r in enumerate(ROCK_R):
    for v in range(3):
        SHAPES.append(('SH_ROCK%d_%d' % (size, v), rock(r, 10 * size + v + 3) if r > 2 else
                       [{(-1, -2), (0, -2), (1, -2), (-2, -1), (2, -1), (-2, 0), (2, 0), (-2, 1), (2, 1), (-1, 2), (0, 2), (1, 2)},
                        {(-1, -2), (0, -2), (-2, -1), (1, -1), (2, -1), (-2, 0), (2, 0), (-1, 1), (2, 1), (-1, 2), (0, 2), (1, 2)},
                        {(0, -2), (1, -2), (-1, -1), (2, -1), (-2, 0), (2, 0), (-2, 1), (1, 1), (-1, 2), (0, 2)}][v]))

BIG_UFO = ['....###....',
           '..#######..',
           '###########',
           '..#######..']
SMALL_UFO = ['..###..',
             '#######',
             '..###..']
def art(rows):
    h, w = len(rows), len(rows[0])
    return {(x - w // 2, y - h // 2) for y, r in enumerate(rows) for x, ch in enumerate(r) if ch == '#'}
SHAPES.append(('SH_UFO_BIG', art(BIG_UFO)))
SHAPES.append(('SH_UFO_SMALL', art(SMALL_UFO)))

# ---- the pictures for the terminal's sprite layer (control code 1C) ----
# 0-31 the ship at its 32 headings, 32-40 the rocks, 41-42 the saucers
# 43 a bullet (shape numbers 0-31, 64-74); no mask: lit pixels are drawn, the rest is
# see-through, like the drawing in fb.  Each has its top left corner at
# (x - ox, y - oy) from the object's place.
PIC_SHAPES = list(range(32)) + list(range(64, 75)) + ['dot']
def pictures():
    out = []
    for sh in PIC_SHAPES:
        px = {(0, 0)} if sh == 'dot' else SHAPES[sh][1]     # 'dot': a bullet
        x0 = min(x for x, y in px); y0 = min(y for x, y in px)
        w = max(x for x, y in px) - x0 + 1; h = max(y for x, y in px) - y0 + 1
        nb = (w + 7) // 8
        rows = []
        for yy in range(h):
            for k in range(nb):
                rows.append(sum(0x80 >> i for i in range(8) if (x0 + k * 8 + i, y0 + yy) in px))
        out.append((-x0, -y0, w, h, rows))
    return out

def bl(vals):
    return ', '.join('$%02X' % (v & 0xFF) for v in vals)

if __name__ == '__main__':
    print('; generated by gen.py')
    print('NDIR = %d' % NDIR)
    print('sin_tab:   ; sin of heading d (d = 0..39, cos(d) = sin(d + 8)), s.7')
    print('        .byte   ' + bl([round(127 * math.sin(2 * math.pi * d / NDIR)) for d in range(NDIR + 8)]))
    # shapes: pixel lists, offsets stored + 8 (0..16)
    offs, data = [], []
    for name, px in SHAPES:
        offs.append(len(data))
        for (x, y) in sorted(px, key=lambda p: (p[1], p[0])):
            assert -8 <= x <= 8 and -8 <= y <= 8
            data.append((x + 8) | (y + 8) << 5)    # x in bits 0-4, y in bits 5-9 (two bytes)
        data.append(None)
    print('NSHAPE = %d' % len(SHAPES))
    for i, (name, px) in enumerate(SHAPES):
        if not name[-1].isdigit() or name.endswith('0') or 'ROCK' in name or 'UFO' in name:
            print('%-12s = %d' % (name, i))
    # store as two parallel byte lists: dx+8, dy+8; $FF ends a shape
    xs = [255 if v is None else (v & 31) for v in data]
    ys = [255 if v is None else (v >> 5) for v in data]
    print('shp_lo:  .byte   ' + bl([o & 255 for o in offs]))
    print('shp_hi:  .byte   ' + bl([o >> 8 for o in offs]))
    print('SHP_BYTES = %d' % len(xs))
    print('shp_dx:')
    for i in range(0, len(xs), 16): print('        .byte   ' + bl(xs[i:i + 16]))
    print('shp_dy:')
    for i in range(0, len(ys), 16): print('        .byte   ' + bl(ys[i:i + 16]))
    print('rock_r:  .byte   ' + bl(ROCK_R))
    # the rocks pre-rendered as block graphics characters, for each of the 8
    # ways a rock can sit in a character cell (x & 1, y & 3): entries of
    # (column offset + 8, row offset + 4, the character), $FF ends a list
    rocks = [px for name, px in SHAPES if 'ROCK' in name]
    lists = []
    for px in rocks:
        for al in range(8):
            ax, ay = al & 1, al >> 1
            cells = {}
            for (x, y) in px:
                X, Y = ax + x, ay + y
                c, r = X // 2, Y // 4
                cells[(c, r)] = cells.get((c, r), 0) | 1 << ((Y % 4) * 2 + (X % 2))
            ent = []
            for (c, r), b in sorted(cells.items(), key=lambda k: (k[0][1], k[0][0])):
                assert -8 <= c <= 8 and -4 <= r <= 4
                ent += [c + 8, r + 4, b]
            lists.append(ent + [255])
    offs = []; flat = []
    for l in lists: offs.append(len(flat)); flat += l
    print('; pre-rendered rocks: list (rock shape * 8 + alignment)')
    print('rk_lo:   .byte   ' + bl([(o) & 255 for o in offs]))
    print('rk_hi:   .byte   ' + bl([(o >> 8) for o in offs]))
    print('RK_BYTES = %d' % len(flat))
    pics = pictures()
    stream = [0x1C, 0x08]                     # CLEAR, then DEFINE each
    for n, (ox, oy, w, h, rows) in enumerate(pics):
        stream += [0x1C, 0x01, n, w, h, 0] + rows
    print('; the sprite pictures (see pictures() in gen.py): %d, %d bytes of the pool' % (len(pics), sum(len(p[4]) for p in pics)))
    print('NPIC = %d' % len(pics))
    print('PIC_ROCK = 32')
    print('PIC_UFO = 41')
    print('PIC_DOT = 43')
    print('pic_ox:  .byte   ' + bl([p[0] for p in pics]))
    print('pic_oy:  .byte   ' + bl([p[1] for p in pics]))
    print('pic_w:   .byte   ' + bl([p[2] for p in pics]))
    print('pic_h:   .byte   ' + bl([p[3] for p in pics]))
    print('SPR_DEFS = %d' % len(stream))
    print('spr_defs:')
    for i in range(0, len(stream), 16): print('        .byte   ' + bl(stream[i:i + 16]))
    print('rk_data:')
    for i in range(0, len(flat), 16): print('        .byte   ' + bl(flat[i:i + 16]))
