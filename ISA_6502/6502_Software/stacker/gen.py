"""Generate stacker_data.inc: piece shapes, square textures and the title
banner for STACKER.   python3 gen.py > stacker_data.inc"""

# the seven pieces, 4 rotations each, as (x, y) in a 4 x 4 box (y down)
PIECES = [
    ('I', [[(0,1),(1,1),(2,1),(3,1)], [(2,0),(2,1),(2,2),(2,3)], [(0,2),(1,2),(2,2),(3,2)], [(1,0),(1,1),(1,2),(1,3)]]),
    ('O', [[(1,0),(2,0),(1,1),(2,1)]] * 4),
    ('T', [[(1,0),(0,1),(1,1),(2,1)], [(1,0),(1,1),(2,1),(1,2)], [(0,1),(1,1),(2,1),(1,2)], [(1,0),(0,1),(1,1),(1,2)]]),
    ('S', [[(1,0),(2,0),(0,1),(1,1)], [(1,0),(1,1),(2,1),(2,2)], [(1,1),(2,1),(0,2),(1,2)], [(0,0),(0,1),(1,1),(1,2)]]),
    ('Z', [[(0,0),(1,0),(1,1),(2,1)], [(2,0),(1,1),(2,1),(1,2)], [(0,1),(1,1),(1,2),(2,2)], [(1,0),(0,1),(1,1),(0,2)]]),
    ('J', [[(0,0),(0,1),(1,1),(2,1)], [(1,0),(2,0),(1,1),(1,2)], [(0,1),(1,1),(2,1),(2,2)], [(1,0),(1,1),(0,2),(1,2)]]),
    ('L', [[(2,0),(0,1),(1,1),(2,1)], [(1,0),(1,1),(1,2),(2,2)], [(0,1),(1,1),(2,1),(0,2)], [(0,0),(1,0),(1,1),(1,2)]]),
]

# square textures, 4 x 4 pixels (the 4th row and column are the gap)
GLYPHS = [
    ['....', '....', '....', '....'],   # 0 empty board square: black
    ['###.', '###.', '###.', '....'],   # 1 I  solid
    ['###.', '#.#.', '###.', '....'],   # 2 O  hollow
    ['###.', '.#..', '###.', '....'],   # 3 T
    ['#.#.', '.#..', '#.#.', '....'],   # 4 S  cross
    ['.#..', '###.', '.#..', '....'],   # 5 Z  plus
    ['###.', '#...', '###.', '....'],   # 6 J
    ['###.', '..#.', '###.', '....'],   # 7 L
    ['#.#.', '....', '#.#.', '....'],   # 8 ghost: where the piece will land
    ['####', '####', '####', '####'],   # 9 flash (a full line) / game over fill
    ['....', '....', '....', '....'],   # 10 blank
]

def chars(rows):
    """4 x 4 pixels -> (left character, right character)"""
    out = []
    for c0 in (0, 2):
        b = 0
        for k in range(4):
            if rows[k][c0] == '#': b |= 1 << (2 * k)
            if rows[k][c0 + 1] == '#': b |= 1 << (2 * k + 1)
        out.append(b)
    return out

FONT = {  # 3 x 5 squares per letter
    'S': ['###', '#..', '###', '..#', '###'],
    'T': ['###', '.#.', '.#.', '.#.', '.#.'],
    'A': ['###', '#.#', '###', '#.#', '#.#'],
    'C': ['###', '#..', '#..', '#..', '###'],
    'K': ['#.#', '#.#', '##.', '#.#', '#.#'],
    'E': ['###', '#..', '##.', '#..', '###'],
    'R': ['##.', '#.#', '##.', '#.#', '#.#'],
}

def bl(vals):
    return ', '.join('$%02X' % v for v in vals)

if __name__ == '__main__':
    print('; generated by gen.py')
    for n in ('x', 'y'):
        print('pc_%s:   ; [piece * 16 + rotation * 4 + square]' % n)
        for name, rots in PIECES:
            print('        .byte   ' + bl([p[0 if n == 'x' else 1] for r in rots for p in r]) + '   ; ' + name)
    g = [chars(r) for r in GLYPHS]
    print('NGLYPH = %d' % len(g))
    print('glyph_l: .byte   ' + bl([a for a, b in g]))
    print('glyph_r: .byte   ' + bl([b for a, b in g]))
    # banner: the word in solid squares
    word = 'STACKER'
    rows = []
    for y in range(5):
        row = []
        for i, ch in enumerate(word):
            for x in range(3):
                row.append(1 if FONT[ch][y][x] == '#' else 10)
            if i < len(word) - 1: row.append(10)
        rows.append(row)
    print('BANNER_W = %d          ; squares' % len(rows[0]))
    print('BANNER_H = 5')
    print('banner:  ; glyph numbers, row by row')
    for r in rows: print('        .byte   ' + bl(r))
