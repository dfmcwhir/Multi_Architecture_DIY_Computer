def rows(t): return [r for r in t.split('\n')]
def tile(t, cx=0):
    p0, p1 = [], []
    for r in rows(t):
        a = b = 0
        for x in range(8):
            ch = r[cx * 8 + x]; v = 0 if ch == '.' else int(ch)
            a = (a << 1) | (v & 1); b = (b << 1) | (v >> 1)
        p0.append(a); p1.append(b)
    return p0, p1

def main():
    p0 = [0] * 2048; p1 = [0] * 2048; attr = [4] * 256
    def put(n, a, b, ps):
        p0[n * 8:n * 8 + 8] = a; p1[n * 8:n * 8 + 8] = b; attr[n] = ps
    for k, t in enumerate(ICONS):
        for h in range(2):
            a, b = tile(t, h)
            put(2 * k + h, a, b, ICON_PS[k])
            put(12 + 2 * k + h, a, b, ICON_PS[k] + 4)
    font = bold_font()
    for i in range(64):
        g = list(font[i * 8:i * 8 + 8])
        put(0x20 + i, g, [0] * 8, 4)
        put(0x60 + i, g, [0] * 8, 6)
        put(0xA0 + i, g, [0] * 8, 5)
    for k, t in enumerate(SB):
        a, b = tile(t); put(0xE0 + k, a, b, 6)
    sp0, sp1 = tile(POINTER)
    pal = []
    for ps in range(4, 16):
        for c in PAL.get(ps, [0, 0, 0, 0]):
            pal += [c >> 8, c & 0xFF]
    out = ['; gui_gfx.inc - made by gen_gui.py (do not edit)']
    def tab(name, vals, per=16):
        out.append(name + ':')
        for i in range(0, len(vals), per):
            out.append('        .byte   ' + ', '.join('$%02X' % v for v in vals[i:i + per]))
    tab('tile_p0', p0); tab('tile_p1', p1); tab('tile_attr', attr)
    tab('spr_p0', sp0); tab('spr_p1', sp1); tab('pal_gui', pal)
    open('gui_gfx.inc', 'w').write('\n'.join(out) + '\n')
    print('gui_gfx.inc:', len(p0) * 2 + 256 + 16 + len(pal), 'bytes')

if __name__ == '__main__':
    main()
