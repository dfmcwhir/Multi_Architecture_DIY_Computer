#!/usr/bin/env python3
"""gen_pico.py - the PICO9918 graphics for MUNCHER -> muncher_gfx.inc
    python gen_pico.py            (python gen_pico.py png: also maze.png)

The screen is Graphics I with the F18A's second tile layer:
  - layer 1: the walls (blue), drawn from maze.py: a tile is 6 x 8 screen
    pixels (a game pixel is 1.5 x 2), so 4 tiles are 3 cells; the maze is
    tile columns 0-38 at screen x 8-241, rows 0-20.  A wall tile gets a line
    one pixel in from each side that faces an open tile, joined at the
    corners.  The status lines (rows 22-23) are layer 1 text, white.
  - layer 2, on top (pattern bits 0 see-through): the dots, the power
    pellets and the ghost house door, in their own colours, so they never
    share a colour with a wall in the same cell.  Each group of 4 tiles is
    3 cells, named from the 4 tiles' codes (0 none, 1 dot, 2 pellet,
    3 door) by the tables dot_n0, dot_n1, dot_n2 (index c0 + 4c1 + 16c2 +
    64c3).  Texts over the maze (READY!, GAME OVER, PAUSED) are layer 2
    text, yellow.
  - the sprites: 8 x 8; the muncher, and each ghost as a body and its eyes.
Patterns (shared by both layers): 0 blank, $20-$5F the font, then the walls,
then the dot layer's (dots, pellets, door in separate groups of 8, since a
group of 8 patterns has one colour)."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'lib'))
sys.path.insert(0, HERE)
from fontgen import bold_font
from maze import full

# colours: 1 black, 2 green, 3 light green, 4 dark blue, 5 light blue,
# 6 dark red, 7 cyan, 8 red, 9 light red, A dark yellow, B yellow,
# C dark green, D magenta, E grey, F white
WALL_COL = 4
DOT_COL = 0xB                   # dots and pellets (the pellets flash)
DOOR_COL = 0xF
TEXT1 = 0xF0                    # layer 1 text: white (background: the backdrop)
TEXT2 = 0xB1                    # layer 2 text: yellow on black
MUNCH_COL = 0xB
GHOST_COL = [8, 3, 7, 0xA]      # red, light green, cyan, dark yellow
SCARED_COL, FLASH_COL, EYES_COL = 5, 0xF, 0xF

OX = 8                          # the maze's screen x
M = full()
H, W = len(M), len(M[0])

def wall(x, y):                 # walls and the door close a wall's side
    return 0 <= x < W and 0 <= y < H and M[y][x] in '#-'

def wall_bitmap():
    bm = [[0] * 256 for _ in range(H * 8)]
    def px(x, y): bm[y][x] = 1
    for ty in range(H):
        for tx in range(W):
            if M[ty][tx] != '#': continue
            x0, y0 = OX + 6 * tx, 8 * ty
            o = lambda dx, dy: not wall(tx + dx, ty + dy)
            xa, xb = (1 if o(-1, 0) else 0), (4 if o(1, 0) else 5)
            ya, yb = (1 if o(0, -1) else 0), (6 if o(0, 1) else 7)
            if o(0, -1):
                for x in range(xa, xb + 1): px(x0 + x, y0 + 1)
            if o(0, 1):
                for x in range(xa, xb + 1): px(x0 + x, y0 + 6)
            if o(-1, 0):
                for y in range(ya, yb + 1): px(x0 + 1, y0 + y)
            if o(1, 0):
                for y in range(ya, yb + 1): px(x0 + 4, y0 + y)
            # inside corners: the neighbours' lines meet here
            for dx, dy, cx, cy in ((-1, -1, 1, 1), (1, -1, 4, 1), (-1, 1, 1, 6), (1, 1, 4, 6)):
                if o(dx, dy) and not o(dx, 0) and not o(0, dy):
                    px(x0 + cx, y0 + cy)
                    px(x0 + (0 if dx < 0 else 5), y0 + cy)
                    px(x0 + cx, y0 + (0 if dy < 0 else 7))
    return bm

# the dot layer's tile drawings (6 x 8)
ITEM = {
    1: ["......", "......", "......", "..##..", "..##..", "......", "......", "......"],
    2: ["......", "..##..", ".####.", ".####.", ".####.", ".####.", "..##..", "......"],
    3: ["......", "......", "......", "######", "######", "......", "......", "......"],
}
TCODE = {'.': 1, 'o': 2, '-': 3}

def cell_pats_of(codes):
    """4 tile codes -> the 3 cells' patterns (8 bytes each) and kinds"""
    row = [[0] * 24 for _ in range(8)]
    kind = [set(), set(), set()]
    for t, c in enumerate(codes):
        if not c: continue
        for y, r in enumerate(ITEM[c]):
            for i, ch in enumerate(r):
                if ch == '#':
                    x = 6 * t + i
                    row[y][x] = 1
                    kind[x // 8].add(c)
    pats = []
    for k in range(3):
        pats.append(tuple(sum(row[y][8 * k + i] << (7 - i) for i in range(8)) for y in range(8)))
    return pats, kind

def main():
    out = ['; generated by gen_pico.py - do not edit', '']
    def tab(name, data, per=16):
        out.append('%s:' % name)
        for i in range(0, len(data), per):
            out.append('        .byte   ' + ', '.join('$%02X' % b for b in data[i:i + per]))
    # ---- walls
    bm = wall_bitmap()
    wpats, wnames = [], []
    WALL0 = 0x60
    for cy in range(H):
        for cx in range(32):
            p = tuple(sum(bm[cy * 8 + r][cx * 8 + c] << (7 - c) for c in range(8)) for r in range(8))
            if not any(p): wnames.append(0); continue
            if p not in wpats: wpats.append(p)
            wnames.append(WALL0 + wpats.index(p))
    nwall = len(wpats)
    # ---- the dot layer: every state each group of 4 tiles can be in
    combos = set()
    for y in range(H):
        for g in range(10):
            codes = [TCODE.get(M[y][4 * g + t], 0) if 4 * g + t < W else 0 for t in range(4)]
            eat = [t for t in range(4) if codes[t] in (1, 2)]
            for m in range(1 << len(eat)):
                c = list(codes)
                for j, t in enumerate(eat):
                    if m >> j & 1: c[t] = 0
                combos.add(tuple(c))
    bykind = {1: [], 2: [], 3: []}          # dots, pellets (any pellet in it), door
    cellpat = {}
    for c in sorted(combos):
        pats, kind = cell_pats_of(c)
        for k in range(3):
            p = pats[k]
            if not any(p): continue
            kd = 2 if 2 in kind[k] else (3 if 3 in kind[k] else 1)
            if p not in bykind[kd]: bykind[kd].append(p)
    base = WALL0 + nwall
    base = (base + 7) & ~7
    gstart = {}
    dpats = []
    for kd in (1, 2, 3):
        gstart[kd] = base + len(dpats)
        dpats += bykind[kd]
        while len(dpats) % 8: dpats.append((0,) * 8)
    assert base + len(dpats) <= 256, base + len(dpats)
    def pid(p):
        if not any(p): return 0
        for kd in (2, 3, 1):
            if p in bykind[kd]: return gstart[kd] + bykind[kd].index(p)
    n0, n1, n2 = [0] * 256, [0] * 256, [0] * 256
    for c in combos:
        pats, kind = cell_pats_of(c)
        k = c[0] | c[1] << 2 | c[2] << 4 | c[3] << 6
        n0[k], n1[k], n2[k] = pid(pats[0]), pid(pats[1]), pid(pats[2])
    # colour tables (32 groups each)
    col1 = [0] * 32
    for gi in range(4, 12): col1[gi] = TEXT1
    for gi in range(WALL0 // 8, (WALL0 + nwall + 7) // 8): col1[gi] = WALL_COL << 4
    col2 = [0] * 32
    for gi in range(4, 12): col2[gi] = TEXT2
    pill_g = []
    for kd, cc in ((1, DOT_COL), (2, DOT_COL), (3, DOOR_COL)):
        for gi in range(gstart[kd] // 8, (gstart[kd] + len(bykind[kd]) + 7) // 8):
            col2[gi] = cc << 4
            if kd == 2: pill_g.append(gi)
    out.append('WALL_PAT0       = $%02X' % WALL0)
    out.append('NWALL           = %d' % nwall)
    out.append('DOT_PAT0        = $%02X' % base)
    out.append('NDOTPAT         = %d' % len(dpats))
    out.append('PILL_G0         = %d       ; the pellets\' colour groups (they flash)' % pill_g[0])
    out.append('NPILL_G         = %d' % len(pill_g))
    out.append('PILL_COL        = $%02X' % (DOT_COL << 4))
    out.append('')
    tab('pat_font', bold_font())
    tab('pat_wall', [b for p in wpats for b in p])
    tab('pat_dots', [b for p in dpats for b in p])
    tab('col_l1', col1)
    tab('col_l2', col2)
    out.append('; layer 1 names for maze rows 0-%d (32 each)' % (H - 1))
    tab('wall_names', wnames, 32)
    out.append('; the dot layer: a tile\'s code (by maze tile type: empty, dot, pellet, wall, door, house)')
    out.append('dot_code:       .byte   0, 1, 2, 0, 3, 0')
    tab('dot_n0', n0)
    tab('dot_n1', n1)
    tab('dot_n2', n2)
    # ---- sprites
    S = sprites()
    out.append('; sprite patterns (8 x 8): SP_x / 2 for the 13 pictures, then blank, the eyes U L D R')
    tab('spr_pat', [b for p in S for b in p])
    out.append('ghost_col:      .byte   ' + ', '.join('$%X' % c for c in GHOST_COL))
    out.append('MUNCH_COL       = $%X' % MUNCH_COL)
    out.append('SCARED_COL      = $%X' % SCARED_COL)
    out.append('FLASH_COL       = $%X' % FLASH_COL)
    out.append('EYES_COL        = $%X' % EYES_COL)
    open(os.path.join(HERE, 'muncher_gfx.inc'), 'w').write('\n'.join(out) + '\n')
    print('walls %d patterns, dot layer %d (from $%02X), %d combos' % (nwall, len(dpats), base, len(combos)))
    if len(sys.argv) > 1: preview(bm, n0, n1, n2, wpats, dpats, base)

def pic(rows):
    return tuple(int(r.replace('#', '1').replace('.', '0'), 2) for r in rows)

def sprites():
    shut = ["..####..", ".######.", "########", "########", "########", "########", ".######.", "..####.."]
    right = ["..####..", ".######.", "#####...", "####....", "####....", "#####...", ".######.", "..####.."]
    left = [r[::-1] for r in right]
    up = [".#....#.", "##....##", "###..###", "###..###", "########", "########", ".######.", "..####.."]
    down = up[::-1]
    die = [
        ["........", "........", "#......#", "###..###", "########", "########", ".######.", "..####.."],
        ["........", "........", "........", "........", "###..###", "########", ".######.", "..####.."],
        ["........", "........", "........", "........", "........", "..####..", ".######.", "..####.."],
        ["........", "........", "........", "........", "........", "........", "...##...", "..####.."],
    ]
    body = ["..####..", ".######.", "#..##..#", "#..##..#", "#..##..#", "########", "########"]
    g1 = body + ["##.##.##"]
    g2 = body + ["#.#..#.#"]
    sbody = ["..####..", ".######.", "########", "##.##.##", "########", "#.#..#.#", "########"]
    s1 = sbody + ["##.##.##"]
    s2 = sbody + ["#.#..#.#"]
    blank = ["........"] * 8
    def eyes(pupils):
        g = [list("........") for _ in range(8)]
        for y in (2, 3, 4):
            for x in (1, 2, 5, 6): g[y][x] = '#'
        for x, y in pupils: g[y][x] = '.'
        return [''.join(r) for r in g]
    E = [eyes([(1, 2), (2, 2), (5, 2), (6, 2)]),     # up
         eyes([(1, 3), (1, 4), (5, 3), (5, 4)]),     # left
         eyes([(1, 4), (2, 4), (5, 4), (6, 4)]),     # down
         eyes([(2, 3), (2, 4), (6, 3), (6, 4)])]     # right
    # in gen.py's order: SHUT UP LEFT DOWN RIGHT DIE1-4 GHOST1-2 SCARED1-2 EYES
    L = [shut, up, left, down, right] + die + [g1, g2, s1, s2, blank] + E
    return [pic(p) for p in L]

def preview(bm, n0, n1, n2, wpats, dpats, base):
    from PIL import Image
    im = Image.new('RGB', (256, 192))
    for y in range(len(bm)):
        for x in range(256):
            if bm[y][x]: im.putpixel((x, y), (33, 33, 222))
    for y in range(H):
        for g in range(10):
            codes = [TCODE.get(M[y][4 * g + t], 0) if 4 * g + t < W else 0 for t in range(4)]
            k = codes[0] | codes[1] << 2 | codes[2] << 4 | codes[3] << 6
            for ci, n in enumerate((n0[k], n1[k], n2[k])):
                if not n: continue
                p = dpats[n - base]
                for r in range(8):
                    for i in range(8):
                        if p[r] >> (7 - i) & 1:
                            im.putpixel((8 + 24 * g + 8 * ci + i, 8 * y + r), (255, 255, 80))
    im.resize((768, 576), Image.NEAREST).save(os.path.join(HERE, 'maze.png'))

if __name__ == '__main__':
    main()
