#!/usr/bin/env python3
"""gen_pico.py - the PICO9918 tables for SPACE ROCKS -> rocks_gfx.inc
    python gen_pico.py
The font (the games' bold one) and the tables that spread a block graphics
character (2 x 4 pixels) over the bitmap: 8 characters = 3 cells across,
each pixel 1.5 screen pixels wide (left, left, right at an even column;
left, right, right at an odd one) and 2 lines high."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'lib'))
from fontgen import bold_font
o = ['; generated by gen_pico.py - do not edit', '']
def tab(name, vals):
    o.append('%s:' % name)
    for i in range(0, len(vals), 16):
        o.append('        .byte   ' + ', '.join('$%02X' % v for v in vals[i:i + 16]))
tab('font', bold_font())
def pix(i, odd):
    L, R = i & 1, (i >> 1) & 1
    return [L, R, R] if odd else [L, L, R]
def spread(name, odd, first, count, top):
    vals = []
    for i in range(4):
        v = 0
        for j, b in enumerate(pix(i, odd)[first:first + count]):
            if b: v |= 1 << (top - j)
        vals.append(v)
    tab(name, vals)
spread('ev_75', 0, 0, 3, 7); spread('od_42', 1, 0, 3, 4); spread('ev_10', 0, 0, 2, 1)
spread('ev_7', 0, 2, 1, 7); spread('od_64', 1, 0, 3, 6); spread('ev_31', 0, 0, 3, 3)
spread('od_0', 1, 0, 1, 0); spread('od_76', 1, 1, 2, 7); spread('ev_53', 0, 0, 3, 5)
spread('od_20', 1, 0, 3, 2)
open(os.path.join(HERE, 'rocks_gfx.inc'), 'w').write('\n'.join(o) + '\n')
print('rocks_gfx.inc written')
