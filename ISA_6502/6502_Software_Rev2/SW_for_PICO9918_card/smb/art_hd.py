def G(rows):
    """rows of '.0123' -> 16 x n grid of values"""
    return [[0 if c == '.' else int(c) for c in r] for r in rows]


def blank(w=16, h=16): return [[0] * w for _ in range(h)]


def bevel(fill=2, light=1, dark=3, w=16, h=16):
    g = [[fill] * w for _ in range(h)]
    for i in range(w): g[0][i] = light; g[h - 1][i] = dark
    for j in range(h): g[j][0] = light; g[j][w - 1] = dark
    g[h - 1][0] = dark; g[0][w - 1] = light
    return g


