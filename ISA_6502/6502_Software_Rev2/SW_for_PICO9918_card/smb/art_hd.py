def chip_castle():
    """the end of a level: a 40 pin chip, 80 x 80 screen pixels, with "6502"
    on it, a notch, and a door"""
    W = H = 80
    p = [[0] * W for _ in range(H)]
    for y in range(8, H):                       # the body: near black, a lighter rim
        for x in range(12, 68):
            p[y][x] = 3
    for x in range(12, 68): p[8][x] = 2
    for y in range(8, H): p[y][12] = 2
    for y in range(12, H - 2, 8):               # the pins: light grey, shaded
        for x in list(range(2, 12)) + list(range(68, 78)):
            for dy in range(4):
                p[y + dy][x] = 1 if dy < 2 else 2
    for y in range(8, 14):                      # the notch
        for x in range(34, 46):
            if (x - 39.5) ** 2 + (y - 8) ** 2 < 25: p[y][x] = 0
    font = {'6': ['###', '#..', '###', '#.#', '###'], '5': ['###', '#..', '###', '..#', '###'],
            '0': ['###', '#.#', '#.#', '#.#', '###'], '2': ['###', '..#', '###', '#..', '###']}
    for i, d in enumerate('6502'):              # the label: light grey
        for y in range(5):
            for x in range(3):
                if font[d][y][x] == '#':
                    for dy in range(2):
                        for dx in range(2):
                            p[24 + 2 * y + dy][24 + i * 8 + 2 * x + dx] = 1
    for y in range(52, H):                      # the door: an arch
        for x in range(32, 48):
            if y >= 58 or (x - 39.5) ** 2 + (y - 58) ** 2 < 64: p[y][x] = 0
    for y in range(52, H):
        for x in range(32, 48):
            if p[y][x] == 3 and any(0 <= y + dy < H and p[y + dy][x + dx] == 0 for dy in (-1, 0, 1) for dx in (-1, 0, 1)):
                p[y][x] = 2
    return p


