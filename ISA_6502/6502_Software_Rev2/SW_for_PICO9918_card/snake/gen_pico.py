#!/usr/bin/env python3
"""gen_pico.py - the font for SNAKE on the PICO9918 -> snake_gfx.inc
    python gen_pico.py"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'lib'))
from fontgen import bold_font
f = bold_font()
o = ['; generated by gen_pico.py - do not edit', '', 'font:']
for i in range(0, len(f), 16):
    o.append('        .byte   ' + ', '.join('$%02X' % v for v in f[i:i + 16]))
open(os.path.join(HERE, 'snake_gfx.inc'), 'w').write('\n'.join(o) + '\n')
print('snake_gfx.inc written')
